import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { areaTargets } from '../src/config';
import { destinationTargets } from '../src/destinations';
import { distanceMeters, findNearbyParking } from '../src/map/nearbyParking';
import type {
  BicycleParkingCollection,
  BicycleParkingFeature,
  BicyclePumpCollection,
  ComfortClass,
  CyclingSegmentCollection,
  CyclingSegmentFeature
} from '../src/types';

const outputPath = resolve('src/generated/seoContent.ts');
const areaRadiusByZoom: Record<number, number> = {
  11: 25_000,
  12: 12_000,
  13: 7_000,
  14: 4_000
};

function segmentCoordinates(feature: CyclingSegmentFeature): [number, number][] {
  return feature.geometry.type === 'LineString'
    ? (feature.geometry.coordinates as [number, number][])
    : (feature.geometry.coordinates.flat() as [number, number][]);
}

function segmentTouchesRadius(
  feature: CyclingSegmentFeature,
  latitude: number,
  longitude: number,
  radiusMeters: number
): boolean {
  return segmentCoordinates(feature).some(
    ([segmentLongitude, segmentLatitude]) =>
      distanceMeters(latitude, longitude, segmentLatitude, segmentLongitude) <= radiusMeters
  );
}

function nearbyParkingSummary(feature: BicycleParkingFeature, distance: number) {
  return {
    address: feature.properties.address,
    capacity: feature.properties.capacity,
    distanceMeters: Math.round(distance),
    municipality: feature.properties.municipality,
    name: feature.properties.name,
    sourceUrl: feature.properties.source_url
  };
}

const [segments, parking, pumps] = await Promise.all([
  readFile('public/data/osm-segments.geojson', 'utf8').then(
    (value) => JSON.parse(value) as CyclingSegmentCollection
  ),
  readFile('public/data/bicycle-parking.geojson', 'utf8').then(
    (value) => JSON.parse(value) as BicycleParkingCollection
  ),
  readFile('public/data/bicycle-pumps.geojson', 'utf8').then(
    (value) => JSON.parse(value) as BicyclePumpCollection
  )
]);

const overallSegmentCounts: Record<ComfortClass, number> = { A: 0, B: 0, C: 0, D: 0 };
segments.features.forEach((feature) => {
  overallSegmentCounts[feature.properties.comfort_class] += 1;
});

const areas = areaTargets.map((area) => {
  const [latitude, longitude] = area.center;
  const radiusMeters = areaRadiusByZoom[area.zoom];
  if (!radiusMeters) throw new Error(`No SEO radius configured for zoom ${area.zoom}.`);

  const areaSegments = segments.features.filter((feature) =>
    segmentTouchesRadius(feature, latitude, longitude, radiusMeters)
  );
  const segmentCounts: Record<ComfortClass, number> = { A: 0, B: 0, C: 0, D: 0 };
  areaSegments.forEach((feature) => {
    segmentCounts[feature.properties.comfort_class] += 1;
  });

  const areaParking = findNearbyParking(
    parking.features,
    latitude,
    longitude,
    parking.features.length,
    radiusMeters
  );
  const areaPumps = pumps.features.filter(({ geometry }) => {
    const [pumpLongitude, pumpLatitude] = geometry.coordinates;
    return distanceMeters(latitude, longitude, pumpLatitude, pumpLongitude) <= radiusMeters;
  });

  return {
    id: area.id,
    nearestParking: areaParking
      .slice(0, 3)
      .map(({ distanceMeters: distance, feature }) => nearbyParkingSummary(feature, distance)),
    parkingCapacity: areaParking.reduce(
      (sum, { feature }) => sum + (feature.properties.capacity ?? 0),
      0
    ),
    parkingCount: areaParking.length,
    pumpCount: areaPumps.length,
    radiusMeters,
    segmentCounts
  };
});

const destinations = destinationTargets.map((destination) => {
  const nearbyParking = findNearbyParking(
    parking.features,
    destination.latitude,
    destination.longitude,
    parking.features.length,
    2_000
  );
  return {
    id: destination.id,
    nearbyParking: nearbyParking
      .slice(0, 5)
      .map(({ distanceMeters: distance, feature }) => nearbyParkingSummary(feature, distance)),
    parkingCapacity: nearbyParking.reduce(
      (sum, { feature }) => sum + (feature.properties.capacity ?? 0),
      0
    ),
    parkingCount: nearbyParking.length,
    radiusMeters: 2_000
  };
});

const content = {
  areas,
  destinations,
  sourceDates: {
    parking: parking.metadata.source_updated_at,
    pumps: pumps.metadata.source_checked,
    roads: segments.features[0]?.properties.source.retrieved_at?.slice(0, 10) ?? 'unknown'
  },
  summary: {
    parkingCount: parking.features.length,
    pumpCount: pumps.features.length,
    segmentCount: segments.features.length,
    segmentCounts: overallSegmentCounts
  }
};

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/generate-seo-content.ts.\nexport const seoContentData = ${JSON.stringify(content, null, 2)} as const;\n`,
  'utf8'
);
console.log(`Wrote crawlable summaries for ${areas.length} areas and ${destinations.length} destinations.`);
